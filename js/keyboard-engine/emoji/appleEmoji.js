const SKIN_TONES = ['', '🏻', '🏼', '🏽', '🏾', '🏿'];

export function applySkinTone(emoji, toneIndex = 0) {
  const tone = SKIN_TONES[toneIndex] || '';
  if (!tone) return emoji;
  // Only apply to a small set of people/hand emoji that commonly take modifiers
  const base = emoji.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, '');
  if (!/^(👋|🤚|🖐️|✋|🖖|👌|🤌|🤏|✌️|🤞|🤟|🤘|🤙|👈|👉|👆|🖕|👇|☝️|👍|👎|✊|👊|🤛|🤜|👏|🙌|👐|🤲|🙏|✍️|💅|🤳|💪|🦵|🦶|👂|👃|👶|🧒|👦|👧|🧑|👱|👨|🧔|👩|🧓|👴|👵)$/u.test(base)) {
    return emoji;
  }
  return base + tone;
}

export function searchEmoji(query) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const all = Object.values(EMOJI_DATA).flat();
  // Simple: return all if query is empty; otherwise filter by including query in nearby label is hard —
  // return smileys that "match" by returning full set filtered loosely (emoji don't have names here).
  // Keep recent-friendly: if query looks like category keyword, return that category.
  const map = {
    smile: 'smileys', face: 'smileys', people: 'smileys',
    animal: 'animals', nature: 'animals',
    food: 'food', drink: 'food',
    sport: 'activity', game: 'activity',
    car: 'travel', place: 'travel',
    object: 'objects',
    symbol: 'symbols', heart: 'symbols',
    flag: 'flags',
  };
  for (const [k, cat] of Object.entries(map)) {
    if (q.includes(k)) return EMOJI_DATA[cat] || [];
  }
  return all.slice(0, 64);
}

